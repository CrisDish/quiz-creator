CREATE DATABASE IF NOT EXISTS quiz_creator CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE quiz_creator;

CREATE TABLE IF NOT EXISTS handouts (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, title VARCHAR(255) NOT NULL, original_name VARCHAR(255) NOT NULL,
 stored_name CHAR(64) NOT NULL UNIQUE, mime_type VARCHAR(120) NOT NULL, file_size BIGINT UNSIGNED NOT NULL,
 extraction_status ENUM('pending','success','partial','failed') NOT NULL DEFAULT 'pending', extraction_error TEXT NULL,
 extracted_text LONGTEXT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS quizzes (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, handout_id BIGINT UNSIGNED NOT NULL, title VARCHAR(255) NOT NULL,
 mode VARCHAR(32) NOT NULL, config_json JSON NOT NULL, original_json LONGTEXT NULL, validation_json JSON NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(handout_id) REFERENCES handouts(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS questions (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, quiz_id BIGINT UNSIGNED NOT NULL, stable_id VARCHAR(80) NOT NULL,
 position INT NOT NULL, question_type VARCHAR(32) NOT NULL, difficulty VARCHAR(20) NOT NULL, question_text TEXT NOT NULL,
 options_json JSON NOT NULL, answer_key_json JSON NOT NULL, explanation TEXT NOT NULL, grading_notes TEXT NULL,
 sources_json JSON NOT NULL, validation_status VARCHAR(32) NOT NULL,
 FOREIGN KEY(quiz_id) REFERENCES quizzes(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS attempts (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, quiz_id BIGINT UNSIGNED NOT NULL, score DECIMAL(7,2) NULL,
 total INT NOT NULL, correct_count INT NOT NULL DEFAULT 0, review_count INT NOT NULL DEFAULT 0,
 submitted_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(quiz_id) REFERENCES quizzes(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS responses (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, attempt_id BIGINT UNSIGNED NOT NULL, question_id BIGINT UNSIGNED NOT NULL,
 response_text TEXT NULL, is_correct TINYINT(1) NULL, review_status VARCHAR(32) NOT NULL DEFAULT 'graded', feedback TEXT NULL,
 FOREIGN KEY(attempt_id) REFERENCES attempts(id) ON DELETE CASCADE,
 FOREIGN KEY(question_id) REFERENCES questions(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS flashcard_progress (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, quiz_id BIGINT UNSIGNED NOT NULL, question_id BIGINT UNSIGNED NOT NULL,
 status ENUM('known','review') NOT NULL, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 UNIQUE KEY(quiz_id, question_id), FOREIGN KEY(quiz_id) REFERENCES quizzes(id) ON DELETE CASCADE,
 FOREIGN KEY(question_id) REFERENCES questions(id) ON DELETE CASCADE
) ENGINE=InnoDB;
